-- Extrato do cliente: cada debito de envio e cada estorno de mensagem que falhou
CREATE TABLE tb_ledger_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT         NOT NULL,
    message_id BIGINT         NOT NULL,
    type       VARCHAR(20)    NOT NULL,
    amount     NUMERIC(38, 2) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ledger_entries_client FOREIGN KEY (client_id) REFERENCES tb_clients (id),
    CONSTRAINT fk_ledger_entries_message FOREIGN KEY (message_id) REFERENCES tb_messages (id),
    CONSTRAINT ck_ledger_entries_type CHECK (type IN ('DEBIT', 'REFUND')),
    CONSTRAINT ck_ledger_entries_amount CHECK (amount > 0)
);

CREATE INDEX ix_ledger_entries_client ON tb_ledger_entries (client_id, created_at DESC);

